const MAX_META_KEYWORDS = 140;
const MAX_META_KEYWORD_CHARS = 7000;

function inferredStockContext(lists: string[][]): StockKeywordContext | null {
  const first = lists[0] ?? [];
  const symbolEntry = first.find((item) => / share price$/i.test(item.trim()));
  const companyEntry = first.find((item) => / stock$/i.test(item.trim()));
  const exchangeEntry = first.find((item) => /^(?:NSE|BSE|NYSE|NASDAQ|LSE)\s+.+$/i.test(item.trim()));
  if (!symbolEntry || !companyEntry || !exchangeEntry) return null;

  const symbol = symbolEntry.replace(/ share price$/i, "").trim();
  const name = companyEntry.replace(/ stock$/i, "").trim();
  const match = exchangeEntry.trim().match(/^(NSE|BSE|NYSE|NASDAQ|LSE)\s+(.+)$/i);
  const exchange = match?.[1];
  const matchedSymbol = match?.[2];
  if (!symbol || !name || !exchange || !matchedSymbol || matchedSymbol.trim().toLowerCase() !== symbol.toLowerCase()) return null;
  return { name, symbol, exchange: exchange.toUpperCase() };
}

/**
 * Comma-joined keyword meta string with duplicate, count and byte-size controls.
 * Stock pages are detected from their existing leading keyword tuple and receive
 * the full company/ticker long-tail family automatically across the entire stock universe.
 */
export function metaKeywords(...lists: string[][]): string {
  const stockContext = inferredStockContext(lists);
  const expandedLists = stockContext ? [stockSearchKeywords(stockContext), ...lists] : lists;
  const seen = new Set<string>();
  const picked: string[] = [];
  let chars = 0;
  for (const list of expandedLists) {
    for (const raw of list) {
      const k = raw.replace(/\s+/g, " ").trim();
      if (!k) continue;
      const key = k.toLowerCase();
      if (seen.has(key)) continue;
      const addedChars = k.length + (picked.length ? 2 : 0);
      if (picked.length >= MAX_META_KEYWORDS || chars + addedChars > MAX_META_KEYWORD_CHARS) {
        return picked.join(", ");
      }
      seen.add(key);
      picked.push(k);
      chars += addedChars;
    }
  }
  return picked.join(", ");
}
