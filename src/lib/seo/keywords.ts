function compactCompanyName(name: string): string {
  const compact = name
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\s+(?:limited|ltd\.?|incorporated|inc\.?|corporation|corp\.?|plc|p\.l\.c\.)$/i, "")
    .trim();
  return compact || name.trim();
}

